#!/usr/bin/env python3
"""Writes the Android adaptive icon from the bundled Newsreader font, matching
tools/make_icon.swift: a serif "k" on cream with the half-filled orange state dot.

Usage: python3 tools/make_android_icon.py
Writes android/app/src/main/res/drawable/ic_launcher_foreground.xml and
ic_launcher_monochrome.xml, and mipmap-anydpi-v26/ic_launcher.xml.
"""
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "android/app/src/main/res"

font = TTFont(ROOT / "Fonts/Newsreader.ttf")
glyphs = font.getGlyphSet()
name = font.getBestCmap()[ord("k")]
upm = font["head"].unitsPerEm

# Geometry measured from App/Assets.xcassets/AppIcon.appiconset/AppIcon.png (1024 px, y down):
# the "k" fills x 220–652, y 230–792; the dot is 150 px wide, centred at (730, 508).
# Android's adaptive canvas is 108 dp and masks may crop to the middle 66 dp, so the 1024
# design is scaled into the central 72 dp.
CANVAS = 108.0
DESIGN = 1024.0
SCALE = 72.0 / DESIGN
OFFSET = (CANVAS - 72.0) / 2
K_TOP, K_BOTTOM, K_LEFT = 230.0, 792.0, 220.0
DOT_CX, DOT_CY, DOT_D, RING = 730.0, 508.0, 150.0, 28.0

bounds = BoundsPen(glyphs)
glyphs[name].draw(bounds)
xmin, ymin, xmax, ymax = bounds.bounds
size = (K_BOTTOM - K_TOP) / (ymax - ymin)  # design px per font unit

# canvas = OFFSET + SCALE * design; design_x = K_LEFT + (x - xmin) * size;
# design_y = K_TOP + (ymax - y) * size.
svg = SVGPathPen(glyphs, ntos=lambda v: f"{v:.2f}")
glyphs[name].draw(TransformPen(svg, (size * SCALE, 0, 0, -size * SCALE,
                                     OFFSET + SCALE * (K_LEFT - xmin * size),
                                     OFFSET + SCALE * (K_TOP + ymax * size))))
k_path = svg.getCommands()

cx, cy = OFFSET + DOT_CX * SCALE, OFFSET + DOT_CY * SCALE
r_out = (DOT_D / 2) * SCALE
r_in = (DOT_D / 2 - RING) * SCALE


def circle(r):
    return f"M{cx - r:.2f},{cy:.2f}a{r:.2f},{r:.2f} 0 1,0 {2 * r:.2f},0a{r:.2f},{r:.2f} 0 1,0 {-2 * r:.2f},0z"


ring = circle(r_out) + circle(r_in)
r_fill = (DOT_D / 2 - RING / 2) * SCALE
half = f"M{cx:.2f},{cy - r_fill:.2f}a{r_fill:.2f},{r_fill:.2f} 0 0,0 0,{2 * r_fill:.2f}z"


def vector(paths):
    # Glyph contours of a variable font overlap: they need nonZero. The ring needs evenOdd.
    body = "\n".join(f'    <path android:fillColor="{c}" android:fillType="{t}" android:pathData="{p}" />' for c, t, p in paths)
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/make_android_icon.py from Fonts/Newsreader.ttf. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
{body}
</vector>
'''


(RES / "drawable").mkdir(parents=True, exist_ok=True)
(RES / "drawable/ic_launcher_foreground.xml").write_text(
    vector([("@color/ink", "nonZero", k_path), ("@color/amber", "evenOdd", ring), ("@color/amber", "nonZero", half)]))
(RES / "drawable/ic_launcher_monochrome.xml").write_text(
    vector([("#FFFFFFFF", "nonZero", k_path), ("#FFFFFFFF", "evenOdd", ring), ("#FFFFFFFF", "nonZero", half)]))
(RES / "mipmap-anydpi-v26").mkdir(parents=True, exist_ok=True)
(RES / "mipmap-anydpi-v26/ic_launcher.xml").write_text('''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/icon_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
''')
print("wrote icon,", len(k_path), "chars of path")
